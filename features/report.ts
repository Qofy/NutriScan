export const selectUpload           = (state: { report: ReportState }) => state.report.upload;
export const selectExtraction       = (state: { report: ReportState }) => state.report.extraction;
export const selectSelectedReport   = (state: { report: ReportState }) => state.report.selectedReport;

// ─── Reducer export ───────────────────────────────────────────────────────────

export default reportSlice.reducer;
